# --- finish ----------------------------------------------------------------------

def _finish(out: Path, tmp_path: Path, *args: str):
    return subprocess.run([sys.executable, "scripts/process/finish.py", *args], cwd=out,
                          capture_output=True, text=True, env=_env(tmp_path))


def test_finish_merges_a_quiet_range_without_a_test_run_end_to_end(project, tmp_path):
    out, bare, git = project
    _commit(git, out, "assets/logo.png", "notes/2026-11-03.md")
    r = _finish(out, tmp_path, "--apply")
    assert r.returncode == 0, r.stdout + r.stderr
    assert "range is quiet" in r.stdout and "no merge certificate" in r.stdout, r.stdout
    assert _remote(bare, "main") == git("rev-parse", "main").stdout.strip()
    assert "m" not in _probe(tmp_path)  # the hook ran the gates, not the merge suite
    assert not list((out / ".git" / "process-certificates").glob("merge/*"))


def test_finish_still_wants_tests_for_code(project, tmp_path):
    out, bare, git = project
    before = _remote(bare, "main")
    _commit(git, out, "assets/logo.png", "app/code.py")
    r = _finish(out, tmp_path, "--apply")
    assert r.returncode == 0 and "stopped before the merge" in r.stdout, r.stdout + r.stderr
    assert _remote(bare, "main") == before


def test_finish_judges_the_range_after_its_rebase(project, tmp_path):
    """The range is the branch's own change since its new fork: upstream code the
    rebase brings in is main's, already tested there."""
    out, bare, git = project
    _commit(git, out, "assets/logo.png")
    git("checkout", "-q", "-b", "upstream", "main")
    _commit(git, out, "app/upstream.py", msg="upstream code")
    git("push", "-q", "--no-verify", "origin", "HEAD:main", env=ROUTE)
    git("checkout", "-q", "feature")
    r = _finish(out, tmp_path, "--apply")
    assert r.returncode == 0 and "rebased" in r.stdout and "range is quiet" in r.stdout, r.stdout + r.stderr
    assert (out / "app/upstream.py").is_file()


def test_finish_merges_a_bookkeeping_only_range_without_areas(render, tmp_path):
    out = render(tmp_path / "work", {"project_name": "d"})
    bare = tmp_path / "origin.git"
    subprocess.run(["git", "init", "-q", "--bare", "-b", "main", str(bare)], check=True)

    def git(*a):
        return subprocess.run(["git", *a], cwd=out, capture_output=True, text=True,
                              env=_env(tmp_path), check=True)
    git("init", "-q", "-b", "main")
    git("config", "user.email", "t@t")
    git("config", "user.name", "t")
    git("add", "-A")
    git("commit", "-q", "-m", "base")
    git("remote", "add", "origin", str(bare))
    git("push", "-q", "origin", "main")
    git("checkout", "-q", "-b", "notes")
    _write(out, ".process-work/journal/2026-11-03.md", "note\n")

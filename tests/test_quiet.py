"""Quiet ranges (#366, v2.84 B): bookkeeping and inert paths run the gates and
no suite — on the merge push and in `finish --apply`. Inert is a file type
(media, prose), named by `areas.inert` at the integration ref, never protected,
never a test input."""
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

PROBE_GATE = {"probe": {"module": None, "exec": [
    sys.executable, "-c", "import os; open(os.environ['PROBE'], 'a').write('g\\n')"]}}
STACK = {
    "paths": ["app/"],
    "runner": [sys.executable, "-c",
               "import os, sys; open(os.environ['PROBE'], 'a').write('t ' + ' '.join(sys.argv[1:]) + '\\n')",
               "{paths}"],
    "tests": ["app_tests/test_*.py"],
    "map": [{"from": "app/{name}.py", "to": ["app_tests/test_{name}.py"]},
            {"from": "app/x/*.py", "to": ["golden/{x}/**"]}],
    "pins": {"docs/policy.png": ["audit"]},
    "unmapped": "skip",
}
MERGE_SUITE = "echo m >> \"$PROBE\""
ROUTE = {"PROCESS_MERGE_ROUTE": "finish"}


def _env(tmp_path: Path, extra: dict | None = None) -> dict:
    env = {k: v for k, v in os.environ.items()
           if not k.startswith(("PROCESS_", "PRE_COMMIT", "SKIP", "GIT_"))}
    return {**env, "PROBE": str(tmp_path / "probe"), "PROCESS_LANE_DIR": str(tmp_path / "lanes"),
            "PYTHONDONTWRITEBYTECODE": "1", "GIT_CONFIG_COUNT": "1",
            "GIT_CONFIG_KEY_0": "commit.gpgsign", "GIT_CONFIG_VALUE_0": "false", **(extra or {})}


def _write(root: Path, rel: str, text: str = "x\n") -> None:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


def _config(inert: list[str] | None, *, suite: bool = True) -> str:
    data: dict = {"stacks": {"app": STACK}}
    if suite:
        data["merge_suite"] = MERGE_SUITE
    if inert is not None:
        data["areas"] = {"inert": inert}
    return json.dumps(data)


@pytest.fixture
def project(render, tmp_path):
    """main on a bare origin with `inert` (assets, notes) declared; `feature` checked out; hooks on."""
    out = render(tmp_path / "work", {"project_name": "d", "modules": {"git_hooks": True}})
    bare = tmp_path / "origin.git"
    subprocess.run(["git", "init", "-q", "--bare", "-b", "main", str(bare)], check=True)
    _write(out, "docs/process/gates.local.json", json.dumps(PROBE_GATE))
    _write(out, "docs/process/testing.local.json", _config(["assets/**", "notes/**", "audit/**", "**/*.png"]))
    _write(out, "app/code.py", "x = 1\n")
    _write(out, "app_tests/test_code.py", "def test_x(): pass\n")

    def git(*a, env=None, check=True):
        return subprocess.run(["git", *a], cwd=out, capture_output=True, text=True,
                              env=_env(tmp_path, env), check=check)
    git("init", "-q", "-b", "main")
    git("config", "user.email", "t@t")
    git("config", "user.name", "t")
    git("add", "-A")
    git("commit", "-q", "-m", "base")
    git("remote", "add", "origin", str(bare))
    git("push", "-q", "--no-verify", "origin", "main")
    git("checkout", "-q", "-b", "feature")
    # as `pre-commit install` leaves it: the framework's pre-push, the guard as pre-push.legacy
    hooks = out / ".git/hooks"
    (hooks / "pre-push").write_text('#!/bin/sh\n# File generated by pre-commit\n'
                                    'exec "$(dirname "$0")/pre-push.legacy" "$@"\n')
    (hooks / "pre-push").chmod(0o755)
    r = subprocess.run([sys.executable, "scripts/process/install_hooks.py"], cwd=out,
                       capture_output=True, text=True, env=_env(tmp_path))
    assert r.returncode == 0 and "pre-push.legacy" in r.stdout, r.stdout + r.stderr
    return out, bare, git


def _land(git, out: Path, config: str) -> None:
    """`config` on main as the integration branch has it; the branch moves on past it."""
    _write(out, "docs/process/testing.local.json", config)
    git("commit", "-qam", "config")
    git("push", "-q", "--no-verify", "origin", "HEAD:main", env=ROUTE)
    git("commit", "-q", "--allow-empty", "-m", "tip")


def _probe(tmp_path: Path) -> list[str]:
    p = tmp_path / "probe"
    lines = p.read_text().splitlines() if p.exists() else []
    p.unlink(missing_ok=True)
    return lines


def _remote(bare: Path, ref: str) -> str:
    return subprocess.run(["git", "--git-dir", str(bare), "rev-parse", "--verify", "-q", ref],
                          capture_output=True, text=True).stdout.strip()


def _classify(out: Path, tmp_path: Path, *paths: str) -> dict[str, str]:
    code = ("import sys, json; sys.path.insert(0, 'scripts/process'); import quiet; "
            "from pathlib import Path; print(json.dumps(quiet.classify(Path('.'), sys.argv[1:])))")
    r = subprocess.run([sys.executable, "-c", code, *paths], cwd=out, capture_output=True,
                       text=True, env=_env(tmp_path))
    assert r.returncode == 0, r.stderr
    return json.loads(r.stdout)


def _commit(git, out: Path, *paths: str, msg: str = "change") -> None:
    for rel in paths:
        _write(out, rel)
    git("add", "-A")
    git("commit", "-qm", msg)


# --- the merge push ----------------------------------------------------------

def test_a_merge_push_of_inert_and_bookkeeping_paths_runs_the_gates_and_no_suite(project, tmp_path):
    out, bare, git = project
    _commit(git, out, "assets/logo.png", ".process-work/journal/2026-11-03.md")
    r = git("push", "origin", "HEAD:main", env=ROUTE, check=False)
    assert r.returncode == 0, r.stderr
    assert _probe(tmp_path) == ["g"], r.stderr  # no `m`: the merge suite did not run
    assert "inert: assets/logo.png" in r.stderr



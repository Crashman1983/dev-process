"""A host that cannot run a stack (#373, v2.85): the stack's own preflight exits 3,
a branch push leaves the stack to the gate host — only when the integration branch
knows that host check unchanged — and nothing counts as passed. A merge never defers."""
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

UNSUITED = [sys.executable, "-c", "import sys; sys.exit(3)"]
PROBE_GATE = {"probe": {"module": None, "exec": [sys.executable, "-c", "pass"]}}


def _runner(tag: str) -> list[str]:
    return [sys.executable, "-c",
            f"import os, sys; open(os.environ['PROBE'], 'a').write('{tag} ' + ' '.join(sys.argv[1:]) + '\\n')",
            "{paths}"]


def _config(backend_preflight=UNSUITED, *, select=None) -> str:
    backend = {"paths": ["backend/"], "runner": _runner("b"), "tests": ["backend/tests/test_*.py"],
               "unmapped": "skip"}
    if backend_preflight is not None:
        backend["preflight"] = backend_preflight
    if select is not None:
        backend["select"] = select
    return json.dumps({"merge_suite": "echo m >> \"$PROBE\"", "stacks": {
        "backend": backend,
        "web": {"paths": ["web/"], "runner": _runner("w"), "tests": ["web/test_*.py"], "unmapped": "skip"}}})


def _env(tmp_path: Path, extra: dict | None = None) -> dict:
    env = {k: v for k, v in os.environ.items()
           if not k.startswith(("PROCESS_", "PRE_COMMIT", "SKIP", "GIT_"))}
    return {**env, "PROBE": str(tmp_path / "probe"), "PROCESS_LANE_DIR": str(tmp_path / "lanes"),
            "PYTHONDONTWRITEBYTECODE": "1", "GIT_CONFIG_COUNT": "1",
            "GIT_CONFIG_KEY_0": "commit.gpgsign", "GIT_CONFIG_VALUE_0": "false", **(extra or {})}


def _write(root: Path, rel: str, text: str = "x\n") -> None:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


@pytest.fixture
def project(render, tmp_path):
    out = render(tmp_path / "work", {"project_name": "d", "modules": {"git_hooks": True}})
    bare = tmp_path / "origin.git"
    subprocess.run(["git", "init", "-q", "--bare", "-b", "main", str(bare)], check=True)
    _write(out, "docs/process/gates.local.json", json.dumps(PROBE_GATE))
    _write(out, "docs/process/testing.local.json", _config())
    _write(out, "backend/tests/test_a.py", "def test_a(): pass\n")
    _write(out, "web/test_w.py", "def test_w(): pass\n")

    def git(*a, env=None, check=True):
        return subprocess.run(["git", *a], cwd=out, capture_output=True, text=True,
                              env=_env(tmp_path, env), check=check)
    git("init", "-q", "-b", "main")
    git("config", "user.email", "t@t")
    git("config", "user.name", "t")
    git("add", "-A")
    git("commit", "-q", "-m", "base")
    git("remote", "add", "origin", str(bare))
    git("push", "-q", "--no-verify", "origin", "main")
    git("checkout", "-q", "-b", "feature")
    # as `pre-commit install` leaves it: the framework's pre-push, the guard as pre-push.legacy
    (out / ".git/hooks/pre-push").write_text('#!/bin/sh\n# File generated by pre-commit\n'
                                             'exec "$(dirname "$0")/pre-push.legacy" "$@"\n')
    (out / ".git/hooks/pre-push").chmod(0o755)
    r = subprocess.run([sys.executable, "scripts/process/install_hooks.py"], cwd=out,
                       capture_output=True, text=True, env=_env(tmp_path))
    assert r.returncode == 0, r.stderr
    return out, bare, git


def _probe(tmp_path: Path) -> list[str]:
    p = tmp_path / "probe"
    lines = p.read_text().splitlines() if p.exists() else []
    p.unlink(missing_ok=True)
    return lines


def _change(git, out: Path, *paths: str, msg: str = "change") -> None:
    for rel in paths:
        _write(out, rel, f"# {msg}\n")
    git("add", "-A")
    git("commit", "-qm", msg)


def _stamps(out: Path) -> str:
    found = list((out / ".git").glob("process-push-stamps*"))
    return "".join(p.read_text() for p in found if p.is_file())


def test_a_branch_push_leaves_an_unsuited_stack_owed_and_stamps_nothing(project, tmp_path):
    out, bare, git = project
    _change(git, out, "backend/tests/test_a.py", "web/test_w.py")
    r = git("push", "origin", "feature", check=False)
    assert r.returncode == 0, r.stderr
    got = _probe(tmp_path)
    assert any(ln.startswith("w ") for ln in got) and not any(ln.startswith("b ") for ln in got), got
    assert "owed on the gate host — backend" in r.stdout + r.stderr
    assert "no stamp — owed on the gate host: backend" in r.stderr, r.stderr
    head = git("rev-parse", "HEAD").stdout.strip()
    assert head not in _stamps(out)


def test_no_certificate_when_a_stack_was_owed(project, tmp_path):
    out, bare, git = project
    _change(git, out, "backend/tests/test_a.py", "web/test_w.py")
    code = ("import sys; sys.path.insert(0, 'scripts/process'); import test_select, testing_config; "
            "from pathlib import Path; root = Path('.'); cfg = testing_config.load(root); owed = []; "
            "rc = test_select.run(root, cfg, test_select.changed_paths(root, None), 'branch', certify=True, owed=owed); "
            "print(rc, owed)")
    r = subprocess.run([sys.executable, "-c", code], cwd=out, capture_output=True, text=True, env=_env(tmp_path))
    assert r.stdout.strip().endswith("0 ['backend']"), r.stdout + r.stderr
    assert "push certificate written" not in r.stdout
    assert not list((out / ".git" / "process-certificates").glob("push/*"))



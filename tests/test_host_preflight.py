def test_a_merge_push_never_defers(project, tmp_path):
    out, bare, git = project
    _change(git, out, "backend/tests/test_a.py")
    r = git("push", "origin", "HEAD:main", env={"PROCESS_MERGE_ROUTE": "finish"}, check=False)
    assert r.returncode != 0 and "a merge runs every stack" in r.stderr, r.stderr
    assert "m" not in _probe(tmp_path)



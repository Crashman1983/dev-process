def test_hook_doctor_sees_installed_pre_commit(render, tmp_path):
    out = _repo(render, tmp_path)
    hooks = Path(_git(out, "rev-parse", "--git-path", "hooks").stdout.strip())
    hooks = hooks if hooks.is_absolute() else out / hooks
    hooks.mkdir(parents=True, exist_ok=True)
    (hooks / "pre-push").write_text("#!/bin/sh\n# File generated by pre-commit\n")
    gi = _load(out)
    # pre-commit's hook without the merge guard in front of it: a note, not a
    # blocker — `merge_route --hook-check` already refuses a push to main the guard
    # did not see; a hard finding here refused every BRANCH push of a clone that
    # updated without running the installer (refute round 2, F4)
    hard, soft = gi.hook_wiring_findings(out)
    assert not hard and any("install_hooks.py" in s for s in soft), (hard, soft)
    r = subprocess.run([sys.executable, "scripts/process/install_hooks.py"], cwd=out,
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    assert (hooks / "pre-push.legacy").is_file()
    assert gi.hook_wiring_findings(out) == ([], [])


